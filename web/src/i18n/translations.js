export function normalizeLanguage(value) {
  const normalized = String(value || "").trim().toLowerCase();
  if (normalized.startsWith("uz")) {
    return "uz";
  }
  if (normalized.startsWith("ru")) {
    return "ru";
  }
  return DEFAULT_LANGUAGE;
}

